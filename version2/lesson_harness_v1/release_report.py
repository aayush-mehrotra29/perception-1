"""Local release audit and model card. No inference, fitting, or network requests.

This audits engineering evidence; it never upgrades synthetic agreement to human
accuracy or equates preserved native arrays with independent TRIBE replication.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path

from . import LEVELS, QUALITIES
from .contract import Timeline

FORMATS = ('video', 'audio', 'text', 'pdf', 'image')


def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def bound_file(root, name, expected):
    root = Path(root).resolve()
    path = (root / name).resolve()
    if not path.is_relative_to(root) or sha(path) != expected:
        raise ValueError('release file identity mismatch: ' + name)
    return path


def audit_bundle(root, artifact_sha, heads):
    root = Path(root)
    manifest = read(root/'manifest.json')
    if manifest['artifact_sha256'] != artifact_sha:
        raise ValueError('example was generated by a different artifact')
    quality = manifest['quality_timeline']
    timeline = Timeline.model_validate(read(bound_file(root, quality['file'], quality['sha256'])))
    if timeline.artifact_sha256 != artifact_sha or timeline.source_sha256 != manifest['source_sha256']:
        raise ValueError('timeline identity mismatch')
    counts = {q: 0 for q in QUALITIES}
    for point in timeline.points:
        for quality_name, value in point.qualities.items():
            if value.value is None:
                continue
            if point.second < 44 or heads[quality_name]['status'] != 'fitted':
                raise ValueError('untrained head or incomplete context received a prediction')
            origins = heads[quality_name]['supervision_origins']
            if sorted(value.supervision_origins) != sorted(origins):
                raise ValueError('supervision origin changed in the export')
            if origins == ['synthetic'] and value.evidence_status == 'human_supported':
                raise ValueError('synthetic output mislabeled as human-supported')
            counts[quality_name] += 1
    if counts != quality['supported_points_by_quality']:
        raise ValueError('supported counts mismatch')
    fmri = manifest['fmri']
    array = bound_file(root, fmri['file'], fmri['sha256'])
    native = read(bound_file(root, fmri['native_manifest'], fmri['native_manifest_sha256']))
    if (sha(array) != native['array_sha256'] or fmri['TRIBE_weights_changed']
            or fmri['observed_fmri'] or fmri['display_interpolation_applied']):
        raise ValueError('native cortical output is changed or mislabeled')
    segments = native['segments']
    if len(segments) != native['shape'][0] or any(s['duration'] <= 0 for s in segments):
        raise ValueError('native clock inconsistent with output shape')
    return {'input_format': timeline.input_format, 'duration_seconds': timeline.duration_seconds,
            'bundle_sha256': sha(root/'manifest.json'), 'supported_points_by_quality': counts,
            'native_array_sha256': sha(array), 'native_shape': native['shape'],
            'native_clock_segments': len(segments), 'native_arrays_and_clock_preserved': True,
            'vertex_order_qualified': native.get('spatial_metadata', {}).get('vertex_order_qualified', False),
            'independent_neural_accuracy_validated': native.get('event_preprocessing_audit', {}).get('independently_validated_neural_accuracy', False),
            'whole_lesson_offline': timeline.analysis_mode == 'whole_lesson_offline'}


def build(model, examples, output, *, teacher_report=None, tests_log=None):
    model, examples, output = map(Path, (model, examples, output))
    if output.exists():
        raise ValueError('preserve old release reports; choose a new output')
    artifact = read(model/'manifest.json')
    artifact_sha = sha(model/'manifest.json')
    if artifact['deployment_status'] != 'fitted' or artifact['synthetic_fixture']:
        raise ValueError('fitted real-corpus deployment artifact required')
    if set(artifact['heads']) != set(QUALITIES):
        raise ValueError('five explicit output slots required')
    for name, digest in artifact['files'].items():
        bound_file(model, name, digest)
    for member in artifact['ensemble']:
        member_path = bound_file(model, member['manifest'], member['sha256'])
        member_manifest = read(member_path)
        bound_file(member_path.parent, 'weights.npz', member_manifest['weights_sha256'])
        for name, digest in member_manifest.get('files', {}).items():
            bound_file(member_path.parent, name, digest)
    transforms = read(model/'transforms/manifest.json')
    bound_file(model/'transforms', 'transforms.npz', transforms['sha256'])
    example_manifest = read(examples/'manifest.json')
    if (not example_manifest['complete'] or example_manifest['artifact_sha256'] != artifact_sha
            or example_manifest['participant_data_sent_to_cloud']):
        raise ValueError('complete matching local example matrix required')
    rows = {r['input_format']: r for r in example_manifest['examples']}
    if set(rows) != set(FORMATS) or len(example_manifest['examples']) != len(FORMATS):
        raise ValueError('five distinct input-format examples required')
    checks = []
    for kind in FORMATS:
        if sha(examples/kind/'manifest.json') != rows[kind]['bundle_sha256']:
            raise ValueError('example manifest changed')
        checks.append(audit_bundle(examples/kind, artifact_sha, artifact['heads']))
    fitted = [q for q in QUALITIES if artifact['heads'][q]['status'] == 'fitted']
    benchmark = read(model/'benchmark.json')
    label_audit = read(model/'label-audit.json')
    teacher_name = label_audit.get('teacher', label_audit.get('teacher_repo', 'local annotation pipeline; see label audit'))
    teacher = read(teacher_report) if teacher_report else None
    if teacher is not None and (not teacher.get('complete') or not teacher.get('gate_passed')):
        raise ValueError('supplied teacher gate is incomplete or failed')
    annotation_scope = None
    if teacher_name == 'two independent AI content reviewers':
        review_root = Path(label_audit['review_directory'])
        review_protocol = read(review_root/'protocol.json')
        public_path = bound_file(review_root, 'public-content.json', review_protocol['public_content_sha256'])
        public = read(public_path)
        texts = ['\n'.join(e.get('text', e.get('quote', '')) for e in r['evidence']) for r in public]
        annotation_scope = {'reviewed_windows': len(public), 'distinct_concatenated_content_texts': len(set(texts)),
            'independent_participant_observations': False, 'windows_overlap': True,
            'public_content_sha256': sha(public_path), 'review_protocol_sha256': sha(review_root/'protocol.json')}
    report = {
        'schema': 'perception-release-evidence-audit-v1',
        'created_at_utc': datetime.now(timezone.utc).isoformat(),
        'artifact': str(model.resolve()), 'artifact_sha256': artifact_sha,
        'architecture_runs': True, 'five_quality_heads_fitted': len(fitted) == 5,
        'fitted_heads': fitted, 'heads': artifact['heads'],
        'all_five_qualities_have_supported_output_in_all_formats': all(all(r['supported_points_by_quality'][q] > 0 for q in QUALITIES) for r in checks),
        'examples': checks, 'benchmark_schema': benchmark.get('schema'),
        'human_endpoints': {q: benchmark.get('endpoints', {}).get(q, {}).get('human') for q in QUALITIES},
        'synthetic_endpoints': {q: benchmark.get('endpoints', {}).get(q, {}).get('synthetic') for q in QUALITIES},
        'synthetic_supervision': {'teacher': teacher_name,
            'distribution_interpretation': label_audit.get('distribution_interpretation', 'model-generated synthetic judgment; not calibrated human uncertainty'),
            'eeg_in_annotation': label_audit.get('eeg_in_annotation'),
            'annotation_scope': annotation_scope,
            'quality_origin_counts': label_audit.get('quality_origin_counts'),
            'label_audit_sha256': sha(model/'label-audit.json')},
        'teacher_diagnostic': None if teacher is None else {
            'path': str(Path(teacher_report).resolve()), 'sha256': sha(teacher_report),
            'gate_passed': teacher.get('gate_passed'),
            'scope': teacher.get('interpretation', 'Functional development diagnostic only.'),
            'human_accuracy_benchmark': False},
        'tests': None if tests_log is None else {'path': str(Path(tests_log).resolve()), 'sha256': sha(tests_log), 'last_line': Path(tests_log).read_text().strip().splitlines()[-1]},
        'human_accuracy_improvement_established': False,
        'measured_fmri_superiority_tested': False,
        'EEG_improves_TRIBE_cortical_predictions': False,
        'neural_predictions_are_measurements': False,
        'student_agents_executed': False,
        'probabilities_calibrated_to_humans': False,
        'minimum_release_gate': 'Five fitted heads; each has supported points in all five input-format engineering examples; artifact and output hashes valid; native cortical arrays/clock preserved.',
        'pending_scientific_gates': [
            'Independent multi-rater construct-valid human supervision for all five qualities.',
            'New-content and new-person evaluation; existing lectures were previously inspected.',
            'Incremental EEG benefit against matched content/TRIBE and reassigned-EEG controls.',
            'Anatomical vertex ordering and independent native-TRIBE equivalence qualification.',
            'Measured fMRI comparison, if a cortical-superiority claim is pursued.'],
        'levels': list(LEVELS), 'context_seconds': 44, 'display_step_seconds': 1,
        'interpretation': 'A content-based experimental forecast, not a measurement of an individual student. Synthetic supervision is model judgment, not measured psychology.',
    }
    report['engineering_release_gate_passed'] = report['five_quality_heads_fitted'] and report['all_five_qualities_have_supported_output_in_all_formats']
    output.mkdir(parents=True)
    (output/'report.json').write_text(json.dumps(report, indent=2, allow_nan=False)+'\n')
    lines = ['# Experimental multimodal lesson model', '',
             f"Engineering release gate: **{'passed' if report['engineering_release_gate_passed'] else 'incomplete'}**. {len(fitted)} of five heads fitted.", '',
             'The system combines content features and an EEG-informed quality network with a separate frozen TRIBE cortical prediction stream. The two branches have different supervision and validation.', '',
             '| Quality | Status | Supervision | Training labels |', '|---|---|---|---:|']
    for q in QUALITIES:
        head=artifact['heads'][q]
        lines.append(f"| {q} | {head['status']} | {', '.join(head.get('supervision_origins', [])) or 'unavailable'} | {head.get('training_labels', 0)} |")
    lines += ['', f'Synthetic supervision source: **{teacher_name}**. ' + report['synthetic_supervision']['distribution_interpretation'] + '.', '']
    if teacher_name == 'two independent AI content reviewers':
        lines += ['The two reviewers used public lesson text and quoted content under a fixed hypothetical learner assumption. They did not receive EEG, participant profiles or human ratings. Their categorical choices were converted to one-hot opinions and reconciled within the fixed disagreement limit. They are AI annotators, not human expert raters. Passing the reused simple/advanced diagnostic does not validate their student-state judgments.', '']
        lines += [f"The annotation set contains {annotation_scope['reviewed_windows']} overlapping windows and {annotation_scope['distinct_concatenated_content_texts']} distinct concatenated text contents. Multiple qualities and repeated/overlapping windows are not independent people, lessons or validation trials.", '']
    human_attention = report['human_endpoints'].get('attention_difficulty') or {}
    if human_attention.get('status') == 'evaluated':
        lines += ['| Matched human attention endpoint | MAE, 0–10 |', '|---|---:|']
        for arm, scores in (human_attention.get('scores') or {}).items():
            if scores.get('MAE_0_10') is not None:
                lines.append(f"| {arm} | {scores['MAE_0_10']:.4f} |")
        lines += ['', 'These are actual held-out forecasts from this artifact’s linked exploratory benchmark. A lower synthetic-label error would measure agreement with the AI annotators, not accuracy against student experience.', '']
    lines += ['', 'The five ordered levels are 0, 2.5, 5, 7.5 and 10. The displayed score is their probability-weighted mean. These model distributions are not calibrated probabilities of a student’s psychological state.', '',
              'Outputs occur at each integer second and use the preceding 44-second context. Warmup and unsupported intervals remain null. One-second output spacing is not one-second psychological resolution. Document, image and text schedules are assumed presentation clocks. Processing is offline and may use pretrained representations with broader context; causal real-time forecasting has not been established.', '',
              'All five format examples were checked for source/model identity, bounded distributions, explicit unavailable values, label provenance, and unchanged native TRIBE arrays and timestamps. This demonstrates integration, not improved learning outcomes.', '',
              'TRIBE outputs are predicted cortical responses, not measured fMRI. The EEG branch does not modify the TRIBE checkpoint. Anatomical vertex ordering and independent neural equivalence remain unqualified in the current caches. Do not advertise brain-region-level accuracy or superiority over TRIBE.', '',
              'Human-label accuracy, synthetic-teacher agreement and functional diagnostics are separate endpoints in report.json. The earlier attention-only experiment did not demonstrate useful EEG benefit. A newly fitted deployment artifact’s training predictions are not validation. A teacher diagnostic only checks task behavior on artificial passages.', '',
              'No attention, engagement, confusion, comprehension or effort score is an observation of a particular student. This release is unsuitable for student assessment, diagnosis, placement or disciplinary decisions.', '',
              f"Artifact: `{model.resolve()}`", f"Artifact manifest SHA-256: `{artifact_sha}`", '',
              'The report’s pending scientific gates remain required before efficacy claims.']
    (output/'MODEL_CARD.md').write_text('\n'.join(lines)+'\n')
    (output/'manifest.json').write_text(json.dumps({'schema':'perception-release-evidence-files-v1','files':{name:sha(output/name) for name in ('report.json','MODEL_CARD.md')}},indent=2)+'\n')
    return report


if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    for name in ('model', 'examples', 'output'):
        parser.add_argument(name,type=Path)
    parser.add_argument('--teacher-report',type=Path);parser.add_argument('--tests-log',type=Path)
    args=parser.parse_args()
    report=build(args.model,args.examples,args.output,teacher_report=args.teacher_report,tests_log=args.tests_log)
    print(json.dumps({'engineering_release_gate_passed':report['engineering_release_gate_passed'],'fitted_heads':report['fitted_heads']}))
