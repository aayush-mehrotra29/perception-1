"""Render an authenticated image/PDF as a declared visual presentation.

Original files stay intact. Poppler preserves PDF page appearance; extracted
text is separately recorded with an explicit unverified reading-order caveat.
No audio, gaze, learner behavior or neural data is generated by this adapter.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

from .edugage_targets import guard
from .presentation import page_schedule
from .worker_contract import PublicMediaRequest, file_sha256, validate_media

FPS = 25


def _run(arguments, *, cwd=None, timeout=120):
    return subprocess.run(arguments, cwd=cwd, capture_output=True, text=True, check=True,
                          timeout=timeout, env={**os.environ, "LC_ALL": "C"}).stdout


def prepare(source: Path, request: PublicMediaRequest, output: Path, *, seconds_per_page):
    from PIL import Image, ImageOps
    import av
    validate_media(source, request)
    if request.media_kind not in {"pdf", "image"}:
        raise ValueError("an authenticated PDF or image is required")
    source = source.resolve()
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        raise RuntimeError("FFmpeg is required for explicit visual presentations")
    if request.media_kind == "pdf":
        required = {name: shutil.which(name) for name in ("pdfinfo", "pdftoppm", "pdftotext")}
        if not all(required.values()):
            raise RuntimeError("Poppler pdfinfo, pdftoppm and pdftotext are required")
        info = _run([required["pdfinfo"], str(source)])
        count = re.search(r"^Pages:\s+(\d+)\s*$", info, flags=re.MULTILINE)
        if count is None:
            raise ValueError("could not establish actual PDF page count")
        page_count = int(count.group(1))
    else:
        page_count = 1
    if page_count > 100:
        raise ValueError("prototype limited to 100 pages")
    schedule = page_schedule(request.sha256, page_count, seconds_per_page=seconds_per_page,
                             input_format=request.media_kind)
    if schedule["duration_seconds"] > 1800:
        raise ValueError("native transport limits presentations to 30 minutes")
    for duration in seconds_per_page:
        if abs(duration * FPS - round(duration * FPS)) > 1e-8:
            raise ValueError("page times must be exact multiples of 0.04 seconds at 25 fps")
    guard(output)
    output.mkdir(parents=True, exist_ok=False)
    pages = output / "pages"
    pages.mkdir()
    records = []
    for index in range(page_count):
        guard(output)
        prefix = pages / f"page-{index:04d}"
        path = prefix.with_suffix(".png")
        if request.media_kind == "pdf":
            _run([required["pdftoppm"], "-f", str(index + 1), "-l", str(index + 1),
                  "-scale-to", "1920", "-singlefile", "-png", str(source), str(prefix)])
            text = _run([required["pdftotext"], "-f", str(index + 1), "-l", str(index + 1),
                         "-enc", "UTF-8", str(source), "-"]).replace("\f", "").strip()
        else:
            with Image.open(source) as original:
                if getattr(original, "n_frames", 1) != 1:
                    raise ValueError("animated images require a native video input")
                upright = ImageOps.exif_transpose(original).convert("RGBA")
                background = Image.new("RGBA", upright.size, "white")
                background.alpha_composite(upright)
                background.convert("RGB").save(path)
            text = ""  # No OCR text is invented for an image.
        with Image.open(path) as page:
            width, height = page.size
        records.append({"source_page_index": index, "file": f"pages/{path.name}",
            "sha256": file_sha256(path), "width": width, "height": height, "text": text,
            "text_basis": "Poppler content-stream extraction; reading order unverified" if request.media_kind == "pdf" else "not_extracted"})
    # Controlled relative filenames avoid ffconcat path quoting ambiguities.
    concat = ["ffconcat version 1.0"]
    for record, slot in zip(records, schedule["pages"]):
        concat.extend([f"file '{Path(record['file']).name}'", f"duration {slot['duration']:.8f}"])
    concat.append(f"file '{Path(records[-1]['file']).name}'")
    (pages / "presentation.ffconcat").write_text("\n".join(concat) + "\n")
    video = output.resolve() / "presentation.mp4"
    guard(output)
    _run([ffmpeg, "-nostdin", "-v", "error", "-n", "-f", "concat", "-safe", "1",
          "-i", "presentation.ffconcat", "-an", "-vf",
          "scale=1920:1080:force_original_aspect_ratio=decrease,pad=1920:1080:(ow-iw)/2:(oh-ih)/2:white,setsar=1,fps=25",
          "-fps_mode", "cfr", "-t", str(schedule["duration_seconds"]), "-c:v", "libx264",
          "-preset", "ultrafast", "-crf", "18", "-pix_fmt", "yuv420p", "-threads", "1",
          "-movflags", "+faststart", str(video)], cwd=pages, timeout=1800)
    # Decode the complete derivative to verify its frame count and actual clock.
    count, last = 0, None
    with av.open(str(video)) as container:
        if len(container.streams.video) != 1 or container.streams.audio:
            raise ValueError("visual presentation must contain one video stream and no audio")
        stream = container.streams.video[0]
        stream.thread_count = 1
        for frame in container.decode(stream):
            if count % 250 == 0:
                guard(output)
            timestamp = float(frame.pts * frame.time_base)
            if abs(timestamp - count / FPS) > 1e-8:
                raise ValueError("rendered page presentation clock changed")
            count += 1
            last = timestamp
    if count != round(schedule["duration_seconds"] * FPS):
        raise ValueError("rendered presentation duration mismatch")
    validate_media(source, request)
    derivative = request.model_copy(update={"source_id": "presentation-" + request.source_id[:90],
        "media_kind": "video", "sha256": file_sha256(video), "size_bytes": video.stat().st_size})
    derivative = PublicMediaRequest.model_validate(derivative.model_dump())
    result = {"schema": "perception-document-presentation-v1", "parent": request.model_dump(),
        "derivative": derivative.model_dump(), "schedule": schedule, "pages": records,
        "rendering": {"canvas": [1920, 1080], "letterbox_color": "white", "fit": "contain_no_crop",
            "fps": FPS, "frame_count": count, "last_frame_seconds": last, "audio_tracks": 0,
            "ffmpeg_version": _run([ffmpeg, "-version"]).splitlines()[0]},
        "source_layout_manually_verified": False, "OCR_performed": False,
        "text_reading_order_verified": False, "scientific_validity_established": False}
    guard(output)
    (output / "request.json").write_text(derivative.model_dump_json(indent=2) + "\n")
    (output / "manifest.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    for name in ("source", "request", "output"):
        parser.add_argument(name, type=Path)
    parser.add_argument("--seconds-per-page", required=True, type=float, nargs="+")
    args = parser.parse_args()
    print(json.dumps(prepare(args.source, PublicMediaRequest.model_validate_json(args.request.read_text()),
                             args.output, seconds_per_page=args.seconds_per_page)))
